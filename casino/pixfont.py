# --- acentos (se componen automáticamente) ---------------------------------
ACUTE = ["..#", ".#."]
GRAVE = ["#..", ".#."]
TILDE = [".#.#", "#.#."]
DIER = ["#.#"]
for base, acc, mk in (("aeiou", "áéíóú", ACUTE), ("AEIOU", "ÁÉÍÓÚ", ACUTE), ("aeiou", "àèìòù", GRAVE),
                      ("n", "ñ", TILDE), ("N", "Ñ", TILDE), ("uU", "üÜ", DIER)):
    for b, a in zip(base, acc):
        top, rows = G[b]
        w = max(len(r) for r in rows)
        upper = b.isupper()
        if b == "i":   # la i pierde el punto
            top, rows = 4, rows[2:]
            w = 3
            rows = ["." + r + "." for r in rows]
        mw = len(mk[0])
        off = max(0, (w - mw + 1) // 2)
        acc_top = 0 if upper else 2
        grid = {}
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    grid[(x, top + y)] = 1
        for y, r in enumerate(mk):
            for x, c in enumerate(r):
                if c == "#":
                    grid[(x + off, acc_top + y)] = 1
        width = max(w, off + mw)
        t0 = min(yy for _, yy in grid)
        t1 = max(yy for _, yy in grid)
        out = []
        for yy in range(t0, t1 + 1):
            out.append("".join("#" if (xx, yy) in grid else "." for xx in range(width)))
        G[a] = (t0, out)

ALIASES = {"—": "-", "–": "-", "“": '"', "”": '"', "‘": "'", "’": "'", "♡": "♥", "♤": "♠", "♢": "♦", "♧": "♣",
           "x": "x"}

# en negrita cada glifo se dibuja dos veces (desplazado 1 píxel): la m y la w necesitan huecos más anchos
BOLD = {
    "m": (4, ["######.", "#..#..#", "#..#..#", "#..#..#", "#..#..#"]),
    "w": (4, ["#..#..#", "#..#..#", "#..#..#", "#..#..#", ".##.##."]),
}

_glyph_cache = {}
_text_cache = {}


def _glyph(ch, bold=False):
    key = (ch, bold and ch in BOLD)
    s = _glyph_cache.get(key)
    if s is None:
        ch2 = ALIASES.get(ch, ch)
        top, rows = BOLD[ch] if key[1] else G.get(ch2, G["?"])
        w = max(len(r) for r in rows)
        s = pygame.Surface((w, CELL_H), pygame.SRCALPHA)
        for y, r in enumerate(rows):
            for x, c in enumerate(r):
                if c == "#":
                    s.set_at((x, top + y), (255, 255, 255, 255))
        _glyph_cache[key] = s
    return s


def width(text, scale=1, bold=False):
    if not text:
        return 0
    w = sum(_glyph(c, bold).get_width() for c in text) + SPACING * (len(text) - 1)
    if bold:
        w += len(text)
    return w * scale


def render(text, color, scale=1, bold=False, shadow=None):
    """Devuelve una superficie con el texto. shadow=(color) añade sombra desplazada 1 píxel de fuente."""
    key = (text, color, scale, bold, shadow)
    s = _text_cache.get(key)
    if s is not None:
        return s
    if len(_text_cache) > 6000:
        _text_cache.clear()
    w = max(1, width(text, 1, bold))
    base = pygame.Surface((w + 1, CELL_H + 1), pygame.SRCALPHA)
    x = 0
    for c in text:
        gl = _glyph(c, bold)
        base.blit(gl, (x, 0))
        if bold:
            base.blit(gl, (x + 1, 0))
        x += gl.get_width() + SPACING + (1 if bold else 0)
    tinted = base.copy()
    tinted.fill((*color[:3], 255), special_flags=pygame.BLEND_RGBA_MULT)
    if shadow:
        out = pygame.Surface(base.get_size(), pygame.SRCALPHA)
        sh = base.copy()
        sh.fill((*shadow[:3], 255), special_flags=pygame.BLEND_RGBA_MULT)
        out.blit(sh, (1, 1))
        out.blit(tinted, (0, 0))
    else:
        out = tinted
    if scale != 1:
        out = pygame.transform.scale(out, (out.get_width() * scale, out.get_height() * scale))
    _text_cache[key] = out
    return out
